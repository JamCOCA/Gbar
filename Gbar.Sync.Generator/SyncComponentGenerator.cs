using System;
using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Gbar.Sync.Generator
{
    /// <summary>
    /// 源生成器：扫描标记了 <c>[SyncComponent]</c> 的 struct 组件，自动生成网络同步所需的
    /// 线格式代码（组件 ID 枚举、标签联合 ComponentEntry、各组件 codec、编解码注册表），
    /// 以及在服务器项目里生成 SyncReader（World/Entity → ComponentEntry[]）。
    /// 未显式指定 ID 的组件按类型全名字母序自动编号，保证两次编译结果一致。
    /// </summary>
    [Generator]
    public sealed class SyncComponentGenerator : IIncrementalGenerator
    {
        private const string AttributeFqn = "Gbar.Net.Protocol.SyncComponentAttribute";
        private const string GeneratedNamespace = "Gbar.Net.Protocol.Entities";
        private const string CoreNamespace = "Gbar.Core.Systems";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterSourceOutput(context.CompilationProvider, (spc, compilation) =>
            {
                // 服务器项目能解析到 Arch.Core.World，此时只需生成 SyncReader；共享层只生成线格式。
                var inCore = compilation.GetTypeByMetadataName("Arch.Core.World") is not null;

                var components = inCore ? FindInReferences(compilation) : FindInCompilation(compilation);
                if (components.Count == 0)
                    return;

                // 字母序保证自动编号确定：同一份源码两次编译得到相同 ID。
                components.Sort((a, b) => string.CompareOrdinal(a.FullName, b.FullName));
                AssignIds(components);

                var source = inCore ? BuildSyncReader(components) : BuildWire(components);
                spc.AddSource(inCore ? "SyncReader.g.cs" : "Sync.Generated.cs", SourceText.From(source, Encoding.UTF8));
            });
        }

        private static void AssignIds(List<ComponentInfo> components)
        {
            var used = new HashSet<int>();
            foreach (var c in components)
            {
                if (c.Id is int id)
                    used.Add(id);
            }

            var next = 1;
            foreach (var c in components)
            {
                if (c.Id is not null)
                    continue;
                while (used.Contains(next))
                    next++;
                c.Id = next;
                used.Add(next);
            }
        }

        private static List<ComponentInfo> FindInCompilation(Compilation compilation)
        {
            var list = new List<ComponentInfo>();
            Walk(compilation.Assembly.GlobalNamespace, list);
            return list;
        }

        private static List<ComponentInfo> FindInReferences(Compilation compilation)
        {
            var list = new List<ComponentInfo>();
            foreach (var asm in compilation.SourceModule.ReferencedAssemblySymbols)
                Walk(asm.GlobalNamespace, list);
            return list;
        }

        private static void Walk(INamespaceSymbol ns, List<ComponentInfo> list)
        {
            foreach (var member in ns.GetMembers())
            {
                if (member is INamespaceSymbol child)
                {
                    Walk(child, list);
                }
                else if (member is INamedTypeSymbol type)
                {
                    var info = TryGet(type);
                    if (info is not null)
                        list.Add(info);
                }
            }
        }

        private static ComponentInfo? TryGet(INamedTypeSymbol type)
        {
            if (type.TypeKind != TypeKind.Struct)
                return null;

            foreach (var attr in type.GetAttributes())
            {
                if (attr.AttributeClass?.ToDisplayString() != AttributeFqn)
                    continue;

                int? id = attr.ConstructorArguments.Length > 0
                    ? (int)(attr.ConstructorArguments[0].Value ?? 0)
                    : null;

                var info = new ComponentInfo { Name = type.Name, FullName = type.ToDisplayString(), Id = id };
                foreach (var m in type.GetMembers())
                {
                    if (m is IFieldSymbol f && !f.IsStatic && !f.IsConst)
                        info.Fields.Add(new FieldInfo { Type = f.Type.ToDisplayString(), Name = f.Name });
                }
                return info;
            }

            return null;
        }

        private static string BuildWire(List<ComponentInfo> components)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("using System.Buffers;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using MemoryPack;");
            sb.AppendLine();
            sb.AppendLine($"namespace {GeneratedNamespace}");
            sb.AppendLine("{");

            sb.AppendLine("    public enum ReplicatedComponent : byte");
            sb.AppendLine("    {");
            sb.AppendLine("        None = 0,");
            foreach (var c in components)
                sb.AppendLine($"        {c.Name} = {c.Id!.Value},");
            sb.AppendLine("    }");
            sb.AppendLine();

            sb.AppendLine("    public struct ComponentEntry");
            sb.AppendLine("    {");
            sb.AppendLine("        public ReplicatedComponent Id;");
            foreach (var c in components)
                sb.AppendLine($"        public {c.FullName} {c.Name};");
            sb.AppendLine();
            foreach (var c in components)
                sb.AppendLine($"        public static ComponentEntry From{c.Name}(in {c.FullName} v) => new ComponentEntry {{ Id = ReplicatedComponent.{c.Name}, {c.Name} = v }};");
            sb.AppendLine("    }");
            sb.AppendLine();

            foreach (var c in components)
                AppendCodec(sb, c);

            sb.AppendLine("    public static class ComponentCodecRegistry");
            sb.AppendLine("    {");
            sb.AppendLine("        public static readonly IReadOnlyDictionary<ReplicatedComponent, IComponentCodec> Codecs =");
            sb.AppendLine("            new Dictionary<ReplicatedComponent, IComponentCodec>");
            sb.AppendLine("            {");
            foreach (var c in components)
                sb.AppendLine($"                [ReplicatedComponent.{c.Name}] = {c.Name}Codec.Instance,");
            sb.AppendLine("            };");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        private static void AppendCodec(StringBuilder sb, ComponentInfo c)
        {
            sb.AppendLine($"    public sealed class {c.Name}Codec : IComponentCodec");
            sb.AppendLine("    {");
            sb.AppendLine($"        public static readonly {c.Name}Codec Instance = new {c.Name}Codec();");
            sb.AppendLine();
            sb.AppendLine($"        public ReplicatedComponent Id => ReplicatedComponent.{c.Name};");
            sb.AppendLine();
            sb.AppendLine("        public void Write<TBufferWriter>(ref MemoryPackWriter<TBufferWriter> writer, in ComponentEntry entry)");
            sb.AppendLine("            where TBufferWriter : IBufferWriter<byte>");
            sb.AppendLine("        {");
            foreach (var f in c.Fields)
                sb.AppendLine($"            writer.WriteUnmanaged(entry.{c.Name}.{f.Name});");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        public void Read(ref MemoryPackReader reader, ref ComponentEntry entry)");
            sb.AppendLine("        {");
            sb.AppendLine($"            entry.{c.Name} = new {c.FullName}");
            sb.AppendLine("            {");
            for (var i = 0; i < c.Fields.Count; i++)
            {
                var f = c.Fields[i];
                var comma = i < c.Fields.Count - 1 ? "," : "";
                sb.AppendLine($"                {f.Name} = reader.ReadUnmanaged<{f.Type}>(){comma}");
            }
            sb.AppendLine("            };");
            sb.AppendLine("        }");
            sb.AppendLine();
            if (c.Fields.Count == 0)
            {
                sb.AppendLine("        public bool Equals(in ComponentEntry a, in ComponentEntry b) => true;");
            }
            else
            {
                sb.Append("        public bool Equals(in ComponentEntry a, in ComponentEntry b) => ");
                for (var i = 0; i < c.Fields.Count; i++)
                {
                    var f = c.Fields[i];
                    if (i > 0)
                        sb.Append(" && ");
                    sb.Append($"a.{c.Name}.{f.Name} == b.{c.Name}.{f.Name}");
                }
                sb.AppendLine(";");
            }
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        private static string BuildSyncReader(List<ComponentInfo> components)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using Arch.Core;");
            sb.AppendLine($"using {GeneratedNamespace};");
            sb.AppendLine();
            sb.AppendLine($"namespace {CoreNamespace}");
            sb.AppendLine("{");
            sb.AppendLine("    internal static class SyncReader");
            sb.AppendLine("    {");
            sb.AppendLine("        public static ComponentEntry[] Read(World world, Entity entity)");
            sb.AppendLine("        {");
            sb.AppendLine("            var list = new List<ComponentEntry>();");
            for (var i = 0; i < components.Count; i++)
            {
                var c = components[i];
                sb.AppendLine($"            if (world.TryGet<{c.FullName}>(entity, out var c{i})) list.Add(ComponentEntry.From{c.Name}(c{i}));");
            }
            sb.AppendLine("            return list.ToArray();");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private sealed class ComponentInfo
        {
            public string Name = "";
            public string FullName = "";
            public int? Id;
            public List<FieldInfo> Fields = new();
        }

        private sealed class FieldInfo
        {
            public string Type = "";
            public string Name = "";
        }
    }
}
